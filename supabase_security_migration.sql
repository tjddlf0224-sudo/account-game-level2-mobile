-- ============================================================
--  supabase_security_migration.sql — 보안·데이터 정합 마이그레이션 (1회 실행)
--  Supabase 대시보드 → SQL Editor 에 "전체"를 붙여넣고 RUN (재실행 안전/멱등)
--
--  ※ 기존 scores / groups 테이블이 이미 있는 라이브 프로젝트
--    (pjagaulfivafamhhiveg) 기준으로 작성됨.
--
--  고치는 문제:
--   [A] wrong_answers·score_history 테이블 미생성
--       → 오답노트/성장 이력의 서버 동기화(wrongnote.js/growth.js)가 전부
--         무음 실패. wrong_answers.sql 의 '적용 완료: 2026-06-24' 주석과 달리
--         실제 DB에는 두 테이블이 없음 → 여기서 생성.
--   [B] scores/groups 의 anon DELETE 정책이 USING(true)
--       → 클라이언트에 노출된 publishable 키만으로 전체 점수·그룹 영구 삭제
--         가능 → 정책 제거 + 비밀번호 검증 RPC(delete_group)로 대체.
--       scores 의 무조건 UPDATE 정책도 제거하고 rename_player RPC 로 대체.
--   [C] groups.teacher_pass 평문 저장 + SELECT 전체 허용
--       → 교수자 비밀번호 전면 노출. 별도 group_secrets 테이블에 bcrypt
--         해시로 분리 저장하고, teacher_pass 컬럼은 조회 차단 + 값 비움.
--         검증은 SECURITY DEFINER RPC(verify_group_pass)로만 수행.
--   [D] 그룹 삭제 후 학생 기기에 남은 hub_group_id 로 upsert_score 호출 시
--       FK(scores_group_id_fkey) 위반으로 점수 저장이 "거짓 성공"으로 유실
--       → FK 를 ON DELETE SET NULL 로 바꾸고, 존재하지 않는 group_id 는
--         트리거로 NULL 처리해 저장 자체는 성공하게 함.
--   [E] score_history.sql:35 / wrong_answers.sql:37 의
--       anon DELETE USING(true) 정책 교정
--       → wrongnote.js/growth.js 가 user_name 필터로 직접 delete 하는 것은
--         유지하되(비로그인 앱이라 행 소유자 식별 불가), 문장 단위 대량 삭제
--         가드 트리거로 테이블 전체 삭제(자명한 필터 공격)를 차단.
--
--  클라이언트(admin.html / group.html / index.html)는 아래 RPC 를 우선
--  호출하고, 이 마이그레이션이 아직 적용되지 않은 DB(RPC 없음, PGRST202)면
--  기존 방식으로 폴백하므로 적용 전·후 모두 동작한다.
-- ============================================================

-- bcrypt 해시용 pgcrypto — Supabase 는 extensions 스키마에 설치돼 있음
create extension if not exists pgcrypto with schema extensions;

set search_path = public, extensions;

